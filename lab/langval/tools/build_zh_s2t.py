#!/usr/bin/env python3
"""Build step: writes js/langlab/zh-s2t.js, the Simplified-to-Traditional character data the
language mirror applies when it cuts Chinese text into words.

    python3 lab/langval/tools/build_zh_s2t.py          # rewrite the data file
    python3 lab/langval/tools/build_zh_s2t.py --check  # exit 1 if the file is out of date

Run it again whenever lexicon-zh.js gains an entry with a character it did not use before.
Needs node and opencc-python-reimplemented (lab/langval/requirements.txt). The app itself needs
neither: the output is plain data and is committed.

Only characters that occur in an entry of lexicon-zh.js (category words and ZH_COMMON) are
covered, because only those can change what is counted. For each such Traditional character T
with a different Simplified form S (OpenCC tw2s):

  SAFE     S -> T   when S is not itself a Traditional character (OpenCC lists no Traditional
                    reading S for S). Applied to every Chinese run before matching. Where several
                    list characters share one S (發 and 髮 are both 发), S goes to OpenCC's default
                    and the others are reached through VARIANT.
  VARIANT  T -> X   X is what a Simplified spelling of T looks like after SAFE: the default
                    Traditional character of S (髮 -> 發), or S itself when S is also a
                    Traditional character and so cannot be converted blindly (後 -> 后, 裡 -> 里,
                    幹 and 乾 -> 干). The engine uses this to add alias spellings of whole entries
                    (頭發 = 頭髮, 以后 = 以後, 干淨 = 乾淨). Single characters get no alias.
"""
import json
import os
import subprocess
import sys

import opencc

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.join(APP, "js", "langlab", "zh-s2t.js")

DUMP = """
import { ZH_CATEGORIES, ZH_COMMON } from %s;
const s = new Set(ZH_COMMON);
for (const d of Object.values(ZH_CATEGORIES)) for (const x of d.words) s.add(x);
process.stdout.write(JSON.stringify([...s]));
"""


def lexicon_words():
    url = json.dumps("file://" + os.path.join(APP, "js", "langlab", "lexicon-zh.js"))
    p = subprocess.run(["node", "--input-type=module", "-e", DUMP % url], stdout=subprocess.PIPE, check=True)
    return json.loads(p.stdout.decode("utf-8"))


def st_candidates():
    path = os.path.join(os.path.dirname(opencc.__file__), "dictionary", "STCharacters.txt")
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 2:
                out[parts[0]] = parts[1].split(" ")
    return out


def build():
    words = lexicon_words()
    freq = {}
    for w in words:
        for ch in w:
            freq[ch] = freq.get(ch, 0) + 1
    tw2s = opencc.OpenCC("tw2s")
    s2tw = opencc.OpenCC("s2tw")
    cands = st_candidates()
    by_s = {}
    for t in sorted(freq):
        s = tw2s.convert(t)
        if len(s) == 1 and s != t:
            by_s.setdefault(s, []).append(t)
    safe, variant = {}, {}
    for s, ts in sorted(by_s.items()):
        if s in freq:
            # the Simplified form is itself used by a list entry (准 in 不准): never convert it blindly
            ambiguous = True
        else:
            ambiguous = s not in cands or s in cands[s]
        if ambiguous:
            for t in ts:
                variant[t] = s
            continue
        default = s2tw.convert(s)
        t0 = default if default in ts else sorted(ts, key=lambda t: (-freq[t], t))[0]
        safe[s] = t0
        for t in ts:
            if t != t0:
                variant[t] = t0
    try:
        from importlib.metadata import version
        ver = version("opencc-python-reimplemented")
    except Exception:
        ver = "version unknown"
    return safe, variant, ver


def render(safe, variant, version):
    pairs = lambda d: "".join(k + v for k, v in sorted(d.items()))
    return (
        "// Generated by lab/langval/tools/build_zh_s2t.py with OpenCC (opencc-python-reimplemented\n"
        "// " + version + ", Apache 2.0: tw2s, s2tw and STCharacters). Do not edit by hand.\n"
        "// Covers only the characters used by entries of lexicon-zh.js. Each string is a run of\n"
        "// two-character pairs.\n"
        "//   ZH_S2T_SAFE     Simplified character, then the Traditional character it is read as. Only\n"
        "//                   characters that Traditional text does not use, so it is applied to all text.\n"
        "//   ZH_S2T_VARIANT  list character, then how it looks when Simplified text has gone through\n"
        "//                   the map above (髮 becomes 發; 後 stays 后 because 后 is also a Traditional\n"
        "//                   character). Used to add alias spellings of whole entries, never of one character.\n"
        f"export const ZH_S2T_SAFE = '{pairs(safe)}';\n"
        f"export const ZH_S2T_VARIANT = '{pairs(variant)}';\n"
        f"export const ZH_S2T_COUNTS = {{ safe: {len(safe)}, variant: {len(variant)} }};\n"
    )


def main():
    text = render(*build())
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            ok = f.read() == text
        print("zh-s2t.js is up to date" if ok else "zh-s2t.js is OUT OF DATE: run build_zh_s2t.py")
        sys.exit(0 if ok else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
