"""Markdown tables for RESULTS.md, built from a results dict. Correlations and AUCs have no leading zero."""
from .metrics import fmt, pct


def ci(v, nd=2):
    return f"{fmt(v[0], nd)} to {fmt(v[1], nd)}"


def render(res):
    out = []
    zh = res["lang"] == "zh"
    unit = "Han characters" if zh else "words"
    out.append(f"<!-- generated by run_analysis.py from results/{res['corpus']}.json; do not edit by hand -->\n")
    out.append(f"Analysed {res['n_analysed']:,} of {res['n_input']:,} texts "
               f"({res['n_other_language']:,} not assigned to '{res['lang']}' by the app's language detector, {res['n_zero_units']:,} with zero units). "
               f"Mean length {res['mean_units']:.1f} {unit}, median {res['median_units']:.0f}. Neutral texts: {res['n_neutral']:,}. "
               f"Bootstrap: {res['B']:,} resamples, seed {res['seed']}. Adjusted interval level: {100 * res['adjusted_level']:.2f}%.\n")

    out.append("### Table 1. Known groups: target against neutral\n")
    out.append("| Category | Target labels | n target | AUC | 95% interval | Adjusted interval | r | r 95% interval | AUC with raw count |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    for r in res["confirmatory"]:
        out.append(f"| `{r['score']}` {r['label']} | {', '.join(r['target_labels']) if len(r['target_labels']) < 5 else str(len(r['target_labels'])) + ' labels'} | {r['n_target']:,} | "
                   f"{fmt(r['auc'])} | {ci(r['auc_ci95'])} | {ci(r['auc_ci_adj'])} | {fmt(r['r'])} | {ci(r['r_ci95'])} | {fmt(r['auc_count'])} |")
    out.append("")

    out.append("### Table 2. Coverage and hit precision\n")
    out.append("| Category | Target texts with a hit | Neutral texts with a hit | Other emotional texts with a hit | All texts with zero hits | Of texts with a hit, share with a target label | Share of all texts with a target label |")
    out.append("|---|---|---|---|---|---|---|")
    for r in res["confirmatory"]:
        ht, hn, ho, z, p = r["hit_target"], r["hit_neutral"], r["hit_other"], r["zero_all"], r["precision"]
        out.append(f"| `{r['score']}` | {pct(ht['share'])} ({pct(ht['low'])} to {pct(ht['high'])}) | {pct(hn['share'])} ({pct(hn['low'])} to {pct(hn['high'])}) | "
                   f"{pct(ho['share'])} | {pct(z['share'])} | {pct(p['share'])} ({pct(p['low'])} to {pct(p['high'])}; {p['n']:,} texts) | {pct(r['base_rate'])} |")
    out.append("")

    out.append("### Table 3. Specificity, discriminant checks and verdict\n")
    out.append("| Category | AUC vs other emotional (95%) | Opposite labels | Opposite AUC vs neutral (95%) | Target minus opposite (adjusted) | Near labels | Near AUC vs neutral (95%) | Target minus near (95%) | Verdict |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    for r in res["confirmatory"]:
        opp = ", ".join(r["opposite_labels"]) if len(r["opposite_labels"]) < 5 else f"{len(r['opposite_labels'])} labels"
        near = ", ".join(r["near_labels"]) if r["near_labels"] else ""
        near_auc = f"{fmt(r['auc_near'])} ({ci(r['auc_near_ci95'])})" if "auc_near" in r else ""
        near_d = f"{fmt(r['diff_near'])} ({ci(r['diff_near_ci95'])})" if "diff_near" in r else ""
        out.append(f"| `{r['score']}` | {fmt(r['auc_specific'])} ({ci(r['auc_specific_ci95'])}) | {opp} | {fmt(r['auc_opposite'])} ({ci(r['auc_opposite_ci95'])}) | "
                   f"{fmt(r['diff_opposite'])} ({ci(r['diff_opposite_ci_adj'])}) | {near} | {near_auc} | {near_d} | **{r['verdict']}** |")
    out.append("")

    out.append("### Table 4. Valence contrast: positive against negative texts\n")
    head = "| Score | n positive | n negative | AUC | 95% interval | Adjusted interval | r | Texts with a score of exactly 0 | Verdict |"
    out.append(head)
    out.append("|---|---|---|---|---|---|---|---|---|")
    for r in res["valence"]:
        out.append(f"| `{r['score']}` | {r['n_positive']:,} | {r['n_negative']:,} | {fmt(r['auc'])} | {ci(r['auc_ci95'])} | {ci(r['auc_ci_adj'])} | "
                   f"{fmt(r['r'])} ({ci(r['r_ci95'])}) | {pct(r['tie_share'])} | **{r['verdict']}** |")
        if "vader_auc" in r:
            out.append(f"| VADER compound (reference) | | | {fmt(r['vader_auc'])} | {ci(r['vader_auc_ci95'])} | | {fmt(r['vader_r'])} ({ci(r['vader_r_ci95'])}) | | no verdict |")
            out.append(f"| tone minus VADER | | | {fmt(r['diff_vader'])} | {ci(r['diff_vader_ci95'])} | | | | |")
    out.append("")

    if res["confirmatory"] and "vader_auc" in res["confirmatory"][0]:
        out.append("### Table 5. VADER as a reference on the same comments\n")
        out.append("| Category | Category AUC vs neutral | VADER AUC vs neutral (95%) | Category minus VADER (95%) | Category AUC vs other emotional | VADER AUC vs other emotional (95%) | Category minus VADER (95%) | VADER: opposite vs neutral | VADER: near vs neutral |")
        out.append("|---|---|---|---|---|---|---|---|---|")
        for r in res["confirmatory"]:
            out.append(f"| `{r['score']}` | {fmt(r['auc'])} | {fmt(r['vader_auc'])} ({ci(r['vader_auc_ci95'])}) | {fmt(r['diff_vader'])} ({ci(r['diff_vader_ci95'])}) | "
                       f"{fmt(r['auc_specific'])} | {fmt(r['vader_auc_specific'])} ({ci(r['vader_auc_specific_ci95'])}) | {fmt(r['diff_vader_specific'])} ({ci(r['diff_vader_specific_ci95'])}) | "
                       f"{fmt(r['vader_auc_opposite'])} | {fmt(r.get('vader_auc_near'))} |")
        out.append("\nVADER is signed so that a higher value should go with the target (minus compound for the negative categories).\n")

    if res["exploratory"]:
        out.append("### Table 6. Exploratory rows (no verdict)\n")
        out.append("| Category | Target labels | n target | AUC vs neutral (95%) | AUC vs other emotional (95%) | r (95%) | Target texts with a hit | Neutral texts with a hit |")
        out.append("|---|---|---|---|---|---|---|---|")
        for r in res["exploratory"]:
            out.append(f"| `{r['score']}` {r['label']} | {', '.join(r['target_labels'])} | {r['n_target']:,} | {fmt(r['auc'])} ({ci(r['auc_ci95'])}) | "
                       f"{fmt(r['auc_specific'])} ({ci(r['auc_specific_ci95'])}) | {fmt(r['r'])} ({ci(r['r_ci95'])}) | {pct(r['hit_target']['share'])} | {pct(r['hit_neutral']['share'])} |")
        out.append("")

    out.append("### Table 7. Descriptive: AUC against neutral for every label (no tests)\n")
    scores = list(res["label_matrix"])
    labels = [lab for lab in res["label_n"] if lab != "neutral"]
    out.append("| Label (n) | " + " | ".join(f"`{s}`" for s in scores) + " |")
    out.append("|---|" + "---|" * len(scores))
    for lab in labels:
        out.append(f"| {lab} ({res['label_n'][lab]:,}) | " + " | ".join(fmt(res["label_matrix"][s][lab]) for s in scores) + " |")
    out.append("\nFor `vader` and `tone` a value under .50 means the label's texts score lower (more negative) than neutral ones.\n")

    if "unconverted_hit_share" in res:
        out.append("### Table 8. Share of utterances with at least one hit, before and after script conversion\n")
        out.append("| Category | Original Simplified text | Converted to Traditional (analysed) |")
        out.append("|---|---|---|")
        for k, v in res["unconverted_hit_share"].items():
            out.append(f"| `{k}` | {pct(v)} | {pct(res['converted_hit_share'][k])} |")
        out.append("")

    out.append("### Word tables (exploratory)\n")
    for r in res["confirmatory"]:
        w = res["words"][r["id"]]
        out.append(f"#### `{r['score']}`: list words by number of texts hit (top 25), and how those texts were labeled\n")
        out.append("| Word | Texts | With a target label | Neutral | Target share | Lift over base rate |")
        out.append("|---|---|---|---|---|---|")
        for d in w["list_words"][:25]:
            out.append(f"| {d['word']} | {d['texts']:,} | {d['target']:,} | {d['neutral']:,} | {pct(d['target_share'], 0)} | {d['lift']:.1f} |")
        out.append("")
        out.append(f"`{r['score']}`: frequent in target texts and not matched by the list (top 25 by z)\n")
        out.append("| Candidate | Target texts | Other texts | Target share | z |")
        out.append("|---|---|---|---|---|")
        for d in w["missing"][:25]:
            out.append(f"| {d['word']} | {d['target']:,} | {d['rest']:,} | {pct(d['target_share'], 0)} | {d['z']:.1f} |")
        out.append("")
    return "\n".join(out) + "\n"
